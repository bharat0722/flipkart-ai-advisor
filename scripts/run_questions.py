"""Run the questions in docs/sample_questions.md through the RAG pipeline and write the answers.

    python scripts/run_questions.py [--questions docs/sample_questions.md] [--out docs/sample_answers.md]

Questions in the "Follow-up" section share one conversation history. Needs the index and an LLM key.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from dotenv import load_dotenv  # noqa: E402

from src.hybrid import make_retriever  # noqa: E402
from src.rag_pipeline import answer_question  # noqa: E402


def parse(path: Path) -> list[tuple[str, list[str]]]:
    sections, current = [], None
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.startswith("## "):
            current = (line[3:].strip(), [])
            sections.append(current)
        elif line.startswith("- ") and current:
            current[1].append(line[2:].strip())
    return sections


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--questions", default=str(ROOT / "docs" / "sample_questions.md"))
    ap.add_argument("--out", default=str(ROOT / "docs" / "sample_answers.md"))
    args = ap.parse_args()
    load_dotenv(ROOT / ".env")
    retriever = make_retriever()
    out = ["# Sample answers", "", "Generated by `scripts/run_questions.py` from `docs/sample_questions.md`.", ""]
    for title, questions in parse(Path(args.questions)):
        out += [f"## {title}", ""]
        history: list[dict] = []
        follow_up = title.lower().startswith("follow-up")
        for q in questions:
            print(f"[{title}] {q}", flush=True)
            try:
                r = answer_question(q, history if follow_up else None, retriever=retriever)
            except Exception as e:  # keep going so one LLM failure doesn't lose the run
                out += [f"### Q: {q}", "", f"**Error:** `{type(e).__name__}: {e}`", ""]
                continue
            if follow_up:
                history += [{"role": "user", "content": q}, {"role": "assistant", "content": r.answer}]
            out += [f"### Q: {q}", "", f"**Reason:** `{r.reason}` · grounded: {r.grounded} · "
                    f"cited: {', '.join(r.cited_product_ids) or 'none'}", "", r.answer.strip(), ""]
            if r.invalid_citations:
                out += [f"**Invalid citations:** {', '.join(r.invalid_citations)}", ""]
    Path(args.out).write_text("\n".join(out), encoding="utf-8")
    print(f"Wrote {args.out}")


if __name__ == "__main__":
    main()
